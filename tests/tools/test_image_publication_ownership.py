@pytest.mark.parametrize("operation", ("read", "write"))
def test_checked_path_operation_forwards_exact_value_and_result(tmp_path, monkeypatch, operation):
    writer = WriteFileTool(workspace=tmp_path, allowed_dir=tmp_path)
    path = tmp_path / "output.png"
    seen: list[str] = []

    def resolve(value: str) -> Path:
        seen.append(value)
        return path

    monkeypatch.setattr(writer, "_resolve_" + operation, resolve)
    result = getattr(writer, "resolve_" + operation + "_path")("unchanged request")
    assert result is path
    assert seen == ["unchanged request"]


@pytest.mark.parametrize("operation", ("read", "write"))
@pytest.mark.parametrize("denial", ("outside", "credential"))
def test_checked_path_operation_keeps_real_boundary_and_credential_refusals(tmp_path, operation, denial):
    workspace = tmp_path / "workspace"
    workspace.mkdir()
    writer = WriteFileTool(workspace=workspace, allowed_dir=workspace)
    path = tmp_path / "outside.png" if denial == "outside" else workspace / ".env"
    with pytest.raises(PermissionError):
        getattr(writer, "resolve_" + operation + "_path")(str(path))
    assert not path.exists()


@pytest.mark.asyncio
@pytest.mark.parametrize("failure", ("none", "changed", "request", "read", "fsync", "replace", "touch", "cancelled"))
async def test_binary_publication_preserves_order_original_errors_and_cleanup(tmp_path, monkeypatch, failure):
    writer = WriteFileTool(workspace=tmp_path, allowed_dir=tmp_path)
    destination = tmp_path / "out.png"
    destination.write_bytes(b"previous")
    source = tmp_path / "source.png"
    source.write_bytes(b"actual generated bytes")
    trace: list[str] = []
    error = asyncio.CancelledError("publication cancelled") if failure == "cancelled" else OSError("publication fault")
    changed = ImageGenerationError("output destination changed during generation")
    guard = writer._mutation_guard
    real_fsync, real_replace, real_touch = filesystem.os.fsync, filesystem.os.replace, writer._record_touch

    @asynccontextmanager
    async def traced_guard(path: Path) -> AsyncIterator[None]:
        assert path == destination
        async with guard(path):
            trace.append("guard")
            try:
                yield
            finally:
                trace.append("release")

    def request() -> str:
        trace.append("request")
        if failure == "request":
            raise error
        return str(tmp_path / "different.png" if failure == "changed" else destination)

    def read_bytes() -> bytes:
        trace.append("read")
        if failure in {"read", "cancelled"}:
            raise error
        return source.read_bytes()

    def changed_error() -> Exception:
        trace.append("changed_error")
        return changed

    def fsync(fd: int) -> None:
        trace.append("fsync")
        if failure == "fsync":
            raise error
        real_fsync(fd)

    def replace(source_path: Path, destination_path: Path) -> None:
        trace.append("replace")
        if failure == "replace":
            raise error
        real_replace(source_path, destination_path)

    def touch(path: Path) -> None:
        trace.append("touch")
        if failure == "touch":
            raise error
        real_touch(path)

    monkeypatch.setattr(writer, "_mutation_guard", traced_guard)
    monkeypatch.setattr(writer, "_record_touch", touch)
    monkeypatch.setattr(filesystem.os, "fsync", fsync)
    monkeypatch.setattr(filesystem.os, "replace", replace)
    if failure == "none":
        await writer.publish_binary_output(
            destination, destination_request=request, read_bytes=read_bytes,
            destination_changed_error=changed_error,
        )
    else:
        with pytest.raises(type(changed if failure == "changed" else error)) as caught:
            await writer.publish_binary_output(
                destination, destination_request=request, read_bytes=read_bytes,
                destination_changed_error=changed_error,
            )
        assert caught.value is (changed if failure == "changed" else error)
    expected = ["guard", "request", "read", "fsync", "replace", "touch", "release"]
    if failure == "changed":
        expected = ["guard", "request", "changed_error", "release"]
    elif failure in {"request", "read", "fsync", "replace", "touch", "cancelled"}:
        last = "read" if failure == "cancelled" else failure
        expected = expected[:expected.index(last) + 1] + ["release"]
    assert trace == expected
    expected_bytes = b"actual generated bytes" if failure in {"none", "touch"} else b"previous"
    assert destination.read_bytes() == expected_bytes
    assert sorted(path.name for path in tmp_path.iterdir()) == ["out.png", "source.png"]


@pytest.mark.asyncio
@pytest.mark.parametrize("cancelled", (False, True))
@pytest.mark.parametrize("explicit_owner", (False, True))
async def test_image_execution_scopes_writer_owner_and_restores_on_real_cancellation(
    tmp_path, monkeypatch, cancelled, explicit_owner,
):
    writer = WriteFileTool(workspace=tmp_path, allowed_dir=tmp_path, lock_owner="default-owner")
    tool = ImageGenerationTool(workspace=tmp_path, config=ImageGenerationToolConfig(), write_tool=writer)
    context = TurnContext(run_id="run-owner", lock_owner="explicit-owner" if explicit_owner else None)
    expected = context.lock_owner or context.run_id
    started = asyncio.Event()
    release = asyncio.Event()
    seen: list[str] = []

    async def execute(**_kwargs: object) -> str:
        seen.append(writer._lock_owner_var.get())
        started.set()
        try:
            await release.wait()
            return "actual result"
        finally:
            seen.append(writer._lock_owner_var.get())

    monkeypatch.setattr(tool, "execute", execute)
    task = asyncio.create_task(tool.execute_with_context(context, prompt="unused"))
    await asyncio.wait_for(started.wait(), timeout=1)
    assert writer._lock_owner_var.get() == "default-owner"
    if cancelled:
        task.cancel()
        with pytest.raises(asyncio.CancelledError):
            await task
    else:
        release.set()
        assert await task == "actual result"
    assert seen == [expected, expected]
    assert writer._lock_owner_var.get() == "default-owner"


@pytest.mark.asyncio
async def test_writer_owner_scope_nests_and_isolates_concurrent_tasks(tmp_path):
    writer = WriteFileTool(workspace=tmp_path, allowed_dir=tmp_path, lock_owner="root")
    scope = writer.execution_owner_scope
    ready = asyncio.Event()
    release = asyncio.Event()

    async def first() -> None:
        async with scope("first"):
            assert writer._lock_owner_var.get() == "first"
            async with scope("nested"):
                assert writer._lock_owner_var.get() == "nested"
            assert writer._lock_owner_var.get() == "first"
            ready.set()
            await release.wait()
            assert writer._lock_owner_var.get() == "first"
        assert writer._lock_owner_var.get() == "root"

    task = asyncio.create_task(first())
    try:
        await asyncio.wait_for(ready.wait(), timeout=1)
        async with scope("second"):
            assert writer._lock_owner_var.get() == "second"
        assert writer._lock_owner_var.get() == "root"
    finally:
        release.set()
        await task


@pytest.mark.parametrize("previous_kind", ("absent", "present", "falsey"))
@pytest.mark.parametrize("enabled", (False, True))
def test_reload_replacement_preserves_writer_selection_and_canonical_construction(
    tmp_path, previous_kind, enabled,
):
    class FalseyImageTool(ImageGenerationTool):
        def __bool__(self) -> bool:
            return False

    original_writer = WriteFileTool(workspace=tmp_path, allowed_dir=tmp_path)
    new_writer = WriteFileTool(workspace=tmp_path, allowed_dir=tmp_path)
    old_config = ImageGenerationToolConfig(model="old-model")
    previous = None
    if previous_kind != "absent":
        tool_type = FalseyImageTool if previous_kind == "falsey" else ImageGenerationTool
        previous = tool_type(workspace=tmp_path, config=old_config, write_tool=original_writer)
    created: list[WriteFileTool] = []

    def make_writer() -> WriteFileTool:
        created.append(new_writer)
        return new_writer

    config = ImageGenerationToolConfig(enabled=enabled, model="new-model")
    provider = ProviderConfig(api_key="test-only-key")
    replacement = ImageGenerationTool.replacement_for(
        previous, workspace=tmp_path, config=config, provider_configs={"openrouter": provider},
        legacy_config=None, make_writer=make_writer,
    )
    assert created == ([] if previous_kind == "present" else [new_writer])
    assert old_config.model == "old-model"
    if enabled:
        assert type(replacement) is ImageGenerationTool
        assert replacement.config is config
        assert replacement.provider_configs == {"openrouter": provider}
        assert replacement._write_tool is (original_writer if previous_kind == "present" else new_writer)
    else:
        assert replacement is None


@pytest.mark.asyncio
async def test_publication_rechecks_real_write_boundary_before_reading_bytes(tmp_path):
    workspace = tmp_path / "workspace"
    workspace.mkdir()
    writer = WriteFileTool(workspace=workspace, allowed_dir=workspace)
    destination = workspace / "out.png"
    read_bytes = MagicMock()

    def forbidden_read() -> bytes:
        read_bytes()
        raise AssertionError("denied publication read artifact bytes")

    with pytest.raises(PermissionError):
        await writer.publish_binary_output(
            destination, destination_request=lambda: str(tmp_path / "outside.png"),
            read_bytes=forbidden_read,
            destination_changed_error=lambda: ImageGenerationError("changed"),
        )
    read_bytes.assert_not_called()
    assert not destination.exists()
    assert list(workspace.iterdir()) == []
